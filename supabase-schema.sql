create table if not exists public.greetings (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 80),
  message text not null check (char_length(btrim(message)) between 1 and 500),
  created_at timestamptz not null default now()
);

alter table public.greetings enable row level security;

grant select, insert on public.greetings to anon;
grant usage, select on sequence public.greetings_id_seq to anon;

drop policy if exists "Public can read greetings" on public.greetings;
create policy "Public can read greetings"
  on public.greetings for select to anon
  using (true);

drop policy if exists "Public can post valid greetings" on public.greetings;
create policy "Public can post valid greetings"
  on public.greetings for insert to anon
  with check (
    char_length(btrim(name)) between 1 and 80
    and char_length(btrim(message)) between 1 and 500
  );
